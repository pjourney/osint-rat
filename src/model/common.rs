//! Types shared across the domain model.

use chrono::{DateTime, SubsecRound, Utc};
use serde::{Deserialize, Serialize};

/// All timestamps are stored in UTC with millisecond precision.
pub type Timestamp = DateTime<Utc>;

/// Returns the current time truncated to milliseconds, so values round-trip through storage.
pub fn now() -> Timestamp {
    Utc::now().trunc_subsecs(3)
}

/// Defines a string-backed enum with a set of known variants and an `Other` fallback.
///
/// Page, entity, source, artifact, and timeline kinds are intentionally open: new kinds can be
/// introduced by collectors, tools, or imported data without a schema change. Each known variant
/// has a stable storage key, a human label, and optional aliases accepted when parsing.
macro_rules! open_enum {
    (
        $(#[$meta:meta])*
        pub enum $name:ident {
            $( $variant:ident => ($key:literal, $label:literal $(, $alias:literal)*) ),+ $(,)?
        }
    ) => {
        $(#[$meta])*
        #[derive(Clone, Debug, PartialEq, Eq, Hash, PartialOrd, Ord, serde::Serialize, serde::Deserialize)]
        #[serde(from = "String", into = "String")]
        pub enum $name {
            $( $variant, )+
            /// A kind that is not built into this version of os-int.
            Other(String),
        }

        impl $name {
            /// The built-in variants, in display order.
            pub const KNOWN: &'static [$name] = &[ $( $name::$variant ),+ ];

            /// The stable storage key.
            pub fn as_str(&self) -> &str {
                match self {
                    $( $name::$variant => $key, )+
                    $name::Other(value) => value.as_str(),
                }
            }

            /// A human-readable label.
            pub fn label(&self) -> &str {
                match self {
                    $( $name::$variant => $label, )+
                    $name::Other(value) => value.as_str(),
                }
            }

            /// Parses a key, label, or alias case-insensitively. Unknown values become `Other`.
            pub fn parse(value: &str) -> Self {
                let normalized = value.trim().to_ascii_lowercase().replace([' ', '-'], "_");
                match normalized.as_str() {
                    $( $key $(| $alias)* => $name::$variant, )+
                    _ => $name::KNOWN
                        .iter()
                        .find(|known| known.label().eq_ignore_ascii_case(value.trim()))
                        .cloned()
                        .unwrap_or($name::Other(normalized)),
                }
            }
        }

        impl From<String> for $name {
            fn from(value: String) -> Self {
                Self::parse(&value)
            }
        }

        impl From<&str> for $name {
            fn from(value: &str) -> Self {
                Self::parse(value)
            }
        }

        impl From<$name> for String {
            fn from(value: $name) -> Self {
                value.as_str().to_string()
            }
        }

        impl std::fmt::Display for $name {
            fn fmt(&self, formatter: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
                formatter.write_str(self.label())
            }
        }
    };
}

pub(crate) use open_enum;

/// Where a piece of information came from. Displayed everywhere so analysts can distinguish
/// collected data, original material, their own notes, and AI inference.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, PartialOrd, Ord, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum Provenance {
    /// Automatically gathered by a collector or external tool.
    Collected,
    /// Original source material supplied by the analyst (a document, a URL they found).
    External,
    /// Written by a human analyst.
    Analyst,
    /// Generated by an AI agent. Always an inference, never a verified fact.
    Agent,
}

impl Provenance {
    pub const ALL: [Provenance; 4] = [
        Provenance::Collected,
        Provenance::External,
        Provenance::Analyst,
        Provenance::Agent,
    ];

    pub fn as_str(self) -> &'static str {
        match self {
            Provenance::Collected => "collected",
            Provenance::External => "external",
            Provenance::Analyst => "analyst",
            Provenance::Agent => "agent",
        }
    }

    /// Short badge used in tables.
    pub fn badge(self) -> &'static str {
        match self {
            Provenance::Collected => "COL",
            Provenance::External => "EXT",
            Provenance::Analyst => "ANL",
            Provenance::Agent => "AI",
        }
    }

    pub fn label(self) -> &'static str {
        match self {
            Provenance::Collected => "Collected data",
            Provenance::External => "Original source material",
            Provenance::Analyst => "Analyst-written",
            Provenance::Agent => "AI-generated inference (unverified)",
        }
    }

    pub fn parse(value: &str) -> Option<Provenance> {
        match value.trim().to_ascii_lowercase().as_str() {
            "collected" | "collector" | "auto" => Some(Provenance::Collected),
            "external" | "original" => Some(Provenance::External),
            "analyst" | "human" | "user" => Some(Provenance::Analyst),
            "agent" | "ai" => Some(Provenance::Agent),
            _ => None,
        }
    }
}

/// Analyst confidence in a finding or relationship.
#[derive(
    Clone, Copy, Debug, Default, PartialEq, Eq, Hash, PartialOrd, Ord, Serialize, Deserialize,
)]
#[serde(rename_all = "snake_case")]
pub enum Confidence {
    #[default]
    Unknown,
    Low,
    Medium,
    High,
    Confirmed,
}

impl Confidence {
    pub const ALL: [Confidence; 5] = [
        Confidence::Unknown,
        Confidence::Low,
        Confidence::Medium,
        Confidence::High,
        Confidence::Confirmed,
    ];

    pub fn as_str(self) -> &'static str {
        match self {
            Confidence::Unknown => "unknown",
            Confidence::Low => "low",
            Confidence::Medium => "medium",
            Confidence::High => "high",
            Confidence::Confirmed => "confirmed",
        }
    }

    pub fn parse(value: &str) -> Option<Confidence> {
        match value.trim().to_ascii_lowercase().as_str() {
            "unknown" | "" | "?" => Some(Confidence::Unknown),
            "low" => Some(Confidence::Low),
            "medium" | "moderate" => Some(Confidence::Medium),
            "high" => Some(Confidence::High),
            "confirmed" | "verified" => Some(Confidence::Confirmed),
            _ => None,
        }
    }
}

/// Ordered key/value metadata attached to sources, entities, and artifacts.
#[derive(Clone, Debug, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(transparent)]
pub struct Fields(pub Vec<(String, String)>);

impl Fields {
    pub fn new() -> Self {
        Self::default()
    }

    pub fn push(&mut self, key: impl Into<String>, value: impl Into<String>) {
        self.0.push((key.into(), value.into()));
    }

    /// Adds the field only when a value is present and non-empty.
    pub fn push_opt(&mut self, key: impl Into<String>, value: Option<impl Into<String>>) {
        if let Some(value) = value {
            let value: String = value.into();
            if !value.trim().is_empty() {
                self.0.push((key.into(), value));
            }
        }
    }

    pub fn get(&self, key: &str) -> Option<&str> {
        self.0
            .iter()
            .find(|(candidate, _)| candidate == key)
            .map(|(_, value)| value.as_str())
    }

    pub fn iter(&self) -> impl Iterator<Item = (&str, &str)> {
        self.0
            .iter()
            .map(|(key, value)| (key.as_str(), value.as_str()))
    }

    pub fn is_empty(&self) -> bool {
        self.0.is_empty()
    }

    pub fn len(&self) -> usize {
        self.0.len()
    }
}

impl FromIterator<(String, String)> for Fields {
    fn from_iter<T: IntoIterator<Item = (String, String)>>(iter: T) -> Self {
        Fields(iter.into_iter().collect())
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    open_enum! {
        pub enum SampleKind {
            Alpha => ("alpha", "Alpha"),
            Beta => ("beta", "Beta Kind", "b"),
        }
    }

    #[test]
    fn open_enum_parses_keys_aliases_and_labels() {
        assert_eq!(SampleKind::parse("ALPHA"), SampleKind::Alpha);
        assert_eq!(SampleKind::parse("b"), SampleKind::Beta);
        assert_eq!(SampleKind::parse("Beta Kind"), SampleKind::Beta);
        assert_eq!(
            SampleKind::parse("gamma"),
            SampleKind::Other("gamma".into())
        );
    }

    #[test]
    fn open_enum_round_trips_through_serde() {
        let input = vec![SampleKind::Beta, SampleKind::Other("custom".into())];
        let json = serde_json::to_string(&input).expect("serialize");
        let actual: Vec<SampleKind> = serde_json::from_str(&json).expect("deserialize");
        assert_eq!(json, r#"["beta","custom"]"#);
        assert_eq!(actual, input);
    }

    #[test]
    fn provenance_and_confidence_parse() {
        assert_eq!(Provenance::parse("AI"), Some(Provenance::Agent));
        assert_eq!(Confidence::parse("Moderate"), Some(Confidence::Medium));
        assert_eq!(Confidence::parse("bogus"), None);
    }

    #[test]
    fn fields_push_opt_skips_empty_values() {
        let mut fields = Fields::new();
        fields.push_opt("present", Some("value"));
        fields.push_opt("blank", Some("  "));
        fields.push_opt("missing", None::<String>);
        assert_eq!(fields.len(), 1);
        assert_eq!(fields.get("present"), Some("value"));
    }
}
